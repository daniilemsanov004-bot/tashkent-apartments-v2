// Разные источники отдают телефон в РАЗНОМ формате: OLX API —
// "+99 893 1804767", Uybor API — обычно просто цифры "998901234567",
// номер из текста объявления — как автор написал, с любыми пробелами
// и дефисами. Без нормализации один и тот же номер из двух источников
// не совпал бы при точном сравнении строк — и вся проверка "один
// номер — много объявлений" (см. db.js: countListingsByPhone) была бы
// бесполезна.

/**
 * @param {string|null|undefined} phone
 * @returns {string|null} последние 9 цифр номера (сам абонентский номер
 *   без кода страны "998" и знаков форматирования), или null, если это
 *   вообще не похоже на телефон.
 */
export function normalizePhone(phone) {
  if (!phone) return null;
  const digits = phone.replace(/\D/g, '');
  if (digits.length < 9) return null;
  return digits.slice(-9);
}
