// Иногда сайты-источники (в первую очередь OLX) сами показывают
// объявление не в той категории, в которой его собирал скрапер —
// например, квартиру можно встретить среди результатов поиска по
// разделу "Коммерческая недвижимость" (продавцы иногда специально
// или по ошибке публикуют жильё туда, чтобы получить больше
// просмотров, либо OLX подмешивает смежные объявления в выдачу).
// Так как property_type на этапе списка (fetchOlxListings/
// fetchRealtingListings) берётся ИСКЛЮЧИТЕЛЬНО из URL раздела, без
// проверки содержимого — такие объявления попадали в базу с неверным
// property_type и полностью выпадали из фильтра "квартиры" в боте.
//
// Этот модуль даёт второе мнение по самому тексту объявления
// (заголовок + описание) — используется как подстраховка в run.js,
// ПОСЛЕ того как текст объявления уже получен, и только для
// источников с несколькими категориями (OLX, Realting). Uybor пока
// собирает только квартиры одним фиксированным URL — там угадывать
// нечего, включать эту проверку для него не нужно.
//
// Если сигналы неоднозначны (например, в тексте есть и "квартира", и
// "офис" — переоборудованная квартира под офис) — возвращаем null и
// ничего не трогаем: URL-категория сайта в этом случае не хуже
// угадывания и рисковать ложной переклассификацией не стоит.

// ВАЖНО: здесь намеренно НЕТ \b (границы слова) на кириллице. В JS
// \b определяется только через ASCII \w ([A-Za-z0-9_]) — кириллица в
// \w не входит, поэтому переход "пробел → кириллическая буква" для
// движка выглядит как "не-слово → не-слово", и \b там попросту не
// срабатывает (проверено: /студи[яи]\b/i.test('студия') === false).
// Из-за этого для "дом" и "псн" (короткие слова, которые могут быть
// частью другого слова, например "домофон") защита от ложных
// совпадений сделана через (?<!...) / (?!...) с явным перечислением
// кириллических букв — lookaround на \b не завязан и работает как
// обычно.
const APARTMENT_RE = /\d+[\s-]*-?\s*комнатн|квартир[а-яё]*|студи[яи]/i;
const HOUSE_RE = /(?<![а-яёa-z])дом(?![а-яёa-z])|коттедж|таунхаус|дача[а-яё]*/i;
const COMMERCIAL_RE =
  /офис[а-яё]*|склад[а-яё]*|магазин[а-яё]*|торгов[а-яё]*|(?<![а-яёa-z])псн(?![а-яёa-z])|под\s+бизнес|коммерческ[а-яё]*|помещени[ея]\s+свободного\s+назначения|автомойк[а-яё]*|салон\s+красот/i;

/**
 * Возвращает 'apartment' | 'house' | 'commercial' | null.
 * null — либо ничего не нашли, либо сигналы противоречивы.
 */
export function guessPropertyType(text) {
  if (!text) return null;
  const matches = [
    APARTMENT_RE.test(text) && 'apartment',
    HOUSE_RE.test(text) && 'house',
    COMMERCIAL_RE.test(text) && 'commercial',
  ].filter(Boolean);
  return matches.length === 1 ? matches[0] : null;
}

/**
 * Если текст объявления однозначно указывает на тип недвижимости,
 * отличный от того, что определила категория сайта (assignedType) —
 * возвращает угаданный тип и логирует расхождение. Иначе возвращает
 * assignedType без изменений.
 */
export function correctPropertyType(assignedType, text, { sourceLabel, url } = {}) {
  const guessed = guessPropertyType(text);
  if (guessed && guessed !== assignedType) {
    console.log(
      `[${sourceLabel || '?'}] объявление, похоже, размещено не в своей категории на сайте ` +
        `(было "${assignedType}", по тексту похоже на "${guessed}"): ${url || ''}`
    );
    return guessed;
  }
  return assignedType;
}
