// Слова-маркеры срочной/мотивированной продажи в тексте объявления —
// сами по себе не значат "дёшево", но в паре с below_market
// (marketStats.js) сильно повышают уверенность, что цена ниже рынка —
// это реальная скидка от продавца, а не ошибка в данных (например,
// неверно распознанная площадь). Работает так же, как agentSignals.js —
// один общий regex по ключевым словам, без внешних вызовов и без
// затрат.
const URGENCY_RE =
  /срочно|срочн(?:ая|ый|ая\s+продажа)|уместен\s+торг|торг\s+уместен|возможен\s+торг|хороший\s+торг|уезжа(?:ю|ем)|нужны\s+деньги|снижен(?:а|ы)?\s+цен|снизил(?:а)?\s+цену|скидк[аи]|горящ(?:ий|ая)\s+вариант|без\s+торга\s+не\s+продаю/i;

/**
 * @param {string|null|undefined} text
 * @returns {string|null} найденная фраза-сигнал или null
 */
export function findUrgencySignal(text) {
  if (!text) return null;
  const m = text.toLowerCase().match(URGENCY_RE);
  return m ? m[0] : null;
}
